def circle_packing_positions(n,spacing):
    """ get fiber center positions for the best-known packing of n equal circles in a circle.
    Args:
    n: number of circles (fibers); supported range 1-37
    spacing: minimum center-to-center distance between circles (spacing=2*r means touching circles of radius r)

    Returns:
    positions: (n,2) array of circle centers
    """
    if n not in CIRCLE_PACKINGS:
        raise ValueError("circle packing for n=%s is not available; supported range is 1-%d" % (n,max(CIRCLE_PACKINGS)))
    return np.array(CIRCLE_PACKINGS[n]) * spacing / 2.
